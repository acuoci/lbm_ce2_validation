class TestH_PivotBasis(unittest.TestCase):
    def test_pivots_and_coordinate_matrix(self):
        pivots = tuple(B.Lhat.rref()[1])
        self.assertEqual(pivots, (0, 1, 2, 4))
        B3 = B.Lhat[:, list(pivots)]
        self.assertEqual(B3.shape, (15, 4))
        K = moment_matrix(("xxy", "xxz", "xyy", "xyz")) * B3
        self.assertEqual(K, sp.Matrix([[2, 0, 0, 0], [0, 2, 0, 0], [0, 0, 1, 0], [0, 0, 0, 3]]))
        self.assertEqual(K.det(), 12)


class TestI_LatticeAliases(unittest.TestCase):
    def test_cubic_aliases(self):
        for c in B.velocities:
            with self.subTest(c=c):
                self.assertEqual(h3(c, "xxy"), h3(c, "yzz"))
                self.assertEqual(h3(c, "xxz"), h3(c, "yyz"))
                self.assertEqual(h3(c, "xyy"), h3(c, "xzz"))
                for lab in ("xxx", "yyy", "zzz"):
                    self.assertEqual(h3(c, lab), 0)

    def test_fully_mixed_channel(self):
        self.assertTrue(any(h3(c, "xyz") != 0 for c in B.velocities))
        q = sp.Matrix(sp.symbols(" ".join(Q_NAMES)))
        T = q[Q_NAMES.index("ux_yz")] + q[Q_NAMES.index("uy_xz")] + q[Q_NAMES.index("uz_xy")]
        m_xyz = (moment_matrix(("xyz",)) * B.Lhat * q)[0]
        self.assertEqual(sp.expand(m_xyz - 3 * T), 0)


class TestJ_CsvReproducibility(unittest.TestCase):
    def test_committed_csv_matches_generated(self):
        self.assertTrue(CSV_D3Q15.exists(), "operators/Lhat_D3Q15.csv is missing")
        text = CSV_D3Q15.read_bytes().decode("utf-8")
        self.assertEqual(text, gen.canonical_csv_text(B))
        rows = list(csv.reader(io.StringIO(text, newline="")))
        self.assertEqual(rows[0], HEADER)
        self.assertEqual(len(rows), 16)
        for i, r in enumerate(rows[1:]):
            self.assertEqual(len(r), 19)
            self.assertEqual(tuple(int(x) for x in r[:3]), B.velocities[i])
            for s in r[3:]:  # exact integer or fraction strings only
                self.assertRegex(s, r"^-?\d+(/\d+)?$")
            self.assertEqual(Fraction(r[3]), Fraction(int(B.w[i].p), int(B.w[i].q)))
            for j, s in enumerate(r[4:]):
                e = B.Lhat[i, j]
                self.assertEqual(Fraction(s), Fraction(int(e.p), int(e.q)), (i, j))
                self.assertEqual(s, str(e))

    def test_same_header_as_existing_operators(self):
        for q in (19, 27):
            with (ROOT / "operators" / f"Lhat_D3Q{q}.csv").open(newline="") as fh:
                self.assertEqual(next(csv.reader(fh)), HEADER)

    def test_check_mode_passes_and_never_writes(self):
        before = hashlib.sha256(CSV_D3Q15.read_bytes()).hexdigest()
        with contextlib.redirect_stdout(io.StringIO()):
            self.assertEqual(gen.main(["--check"]), 0)
        self.assertEqual(hashlib.sha256(CSV_D3Q15.read_bytes()).hexdigest(), before)

    def test_write_roundtrip_and_tamper_detection(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "Lhat_D3Q15.csv"
            with contextlib.redirect_stdout(io.StringIO()):
                self.assertEqual(gen.main(["--write", "--csv", str(path)]), 0)
            self.assertEqual(path.read_bytes(), CSV_D3Q15.read_bytes())
            text = path.read_text(encoding="utf-8")
            path.write_bytes(text.replace("3/8", "1/3", 1).encode("utf-8"))
            with contextlib.redirect_stdout(io.StringIO()):
                self.assertNotEqual(gen.main(["--check", "--csv", str(path)]), 0)
            missing = Path(tmp) / "missing.csv"
            with contextlib.redirect_stdout(io.StringIO()):
                self.assertNotEqual(gen.main(["--check", "--csv", str(missing)]), 0)
            self.assertFalse(missing.exists())


class TestK_ExperimentIICompatibility(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        import numpy as np
        cls.np = np
        cls.lat = load_lattice_quietly(EXP2, "exp2_test_d3q15", CSV_D3Q15)

    def test_shapes_and_name(self):
        lat = self.lat
        self.assertEqual(lat.name, "D3Q15")
        self.assertEqual(lat.c.shape, (15, 3))
        self.assertEqual(lat.w.shape, (15,))
        self.assertEqual(lat.lhat.shape, (15, 15))
        self.assertEqual(list(lat.q_names), Q_NAMES)
        self.assertTrue(self.np.array_equal(lat.c, self.np.array(B.velocities)))

    def test_float_data_bit_identical(self):
        np = self.np
        self.assertTrue(np.array_equal(self.lat.w, np.array([float(x) for x in B.w])))
        self.assertTrue(np.array_equal(self.lat.lhat, np.array(B.Lhat.tolist(), dtype=float)))

    def test_float_projectors_match_exact(self):
        np = self.np
        exact = {
            "Winv": B.Winv, "P_eq": B.P_eq, "P_le1": B.P_le1, "P_le2": B.P_le2,
            "P2": B.P_le2 - B.P_le1, "PK": B.PK, "N": sp.eye(15) - B.P_eq,
        }
        for attr, M in exact.items():
            with self.subTest(projector=attr):
                res = np.max(np.abs(getattr(self.lat, attr) - np.array(M.tolist(), dtype=float)))
                self.assertLessEqual(res, 1e-12)

    def test_experiment_iii_loader_also_reads_file(self):
        lat3 = load_lattice_quietly(EXP3, "exp3_test_d3q15", CSV_D3Q15)
        self.assertEqual(lat3.name, "D3Q15")
        self.assertTrue(self.np.array_equal(lat3.lhat, self.lat.lhat))


